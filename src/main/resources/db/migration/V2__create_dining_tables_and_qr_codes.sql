CREATE TABLE dining_tables(
    table_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY ,
    table_number VARCHAR(255) NOT NULL UNIQUE,
    seating_capacity SMALLINT NOT NULL CHECK ( seating_capacity > 0 ),
    status VARCHAR(50) NOT NULL DEFAULT 'INACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE qr_codes(
    qr_code_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY ,
    table_id BIGINT NOT NULL UNIQUE ,
    qr_token UUID NOT NULL UNIQUE DEFAULT GEN_RANDOM_UUID(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (table_id) REFERENCES dining_tables(table_id) ON DELETE CASCADE
);